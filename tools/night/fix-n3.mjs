const files = new Map();
const read = (no) => {
  if (!files.has(no)) files.set(no, fs.readFileSync(path.join(DIR, `${no}.mjs`), 'utf8'));
  return files.get(no);
};

let sw = 0;
for (const [no, from, to] of SWAP) {
  const src = read(no);
  if (!src.includes(from)) { console.log(`★ ${no}.mjs 에서 못 찾음: ${from.slice(0, 30)}…`); continue; }
  files.set(no, src.replace(from, to));
  sw++;
}

let tl = 0;
for (const no of Object.keys(TAIL).map(Number).sort((a, b) => a - b)) {
  let src = read(no);
  const idx = src.lastIndexOf('      ],\n');
  if (idx < 0) { console.log(`★ ${no}.mjs 구역 끝을 못 찾음`); continue; }
  const add = TAIL[no].map((t) => `        ${JSON.stringify(t).replace(/"/g, "'")},\n`).join('');
  files.set(no, src.slice(0, idx) + add + src.slice(idx));
  tl++;
}

if (APPLY) for (const [no, src] of files) fs.writeFileSync(path.join(DIR, `${no}.mjs`), src, 'utf8');
console.log(`문장 교체 ${sw}건 / 문단 덧붙임 ${tl}개 파일${APPLY ? ' — 저장함' : ' (--apply 필요)'}`);
